#!/usr/bin/env python3
"""Sync registered teams from the registry.

Lists teams/*.yaml in javaBin/registry and writes
registered-teams.auto.tfvars. This drives team-scoped IAM role creation
(CI roles, ECS execution roles).

Source of truth: the registry. GitHub org teams also include non-app teams
(owners, developer, ...) that must not get AWS CI roles.

Usage: sync-registered-teams.py <tfvars-output-path>

Requires: GITHUB_TOKEN env var (read access to javaBin/registry).
"""

import json
import logging
import os
import re
import sys
import urllib.request

logger = logging.getLogger(__name__)
logging.basicConfig(level=logging.INFO, format="%(message)s")

GITHUB_ORG = os.environ.get("GITHUB_ORG", "javaBin")
GITHUB_API = "https://api.github.com"

# Platform-internal teams that don't get app CI roles
EXCLUDED_TEAMS = {"platform"}


def github_get(path, token):
    """Paginated GitHub API GET."""
    results = []
    url = f"{GITHUB_API}{path}"
    while url:
        req = urllib.request.Request(url)
        req.add_header("Authorization", f"token {token}")
        req.add_header("Accept", "application/vnd.github+json")
        with urllib.request.urlopen(req) as resp:
            results.extend(json.loads(resp.read()))
            link = resp.headers.get("Link", "")
            url = None
            for part in link.split(","):
                if 'rel="next"' in part:
                    url = part.split("<")[1].split(">")[0]
    return results


REGISTRY_REPO = os.environ.get("REGISTRY_REPO", "registry")
TEAM_NAME = re.compile(r"^[a-z]{1,12}$")


def get_teams(token):
    """Registry team names (teams/<name>.yaml), excluding platform-internal ones."""
    files = github_get(f"/repos/{GITHUB_ORG}/{REGISTRY_REPO}/contents/teams", token)
    names = [f["name"][:-5] for f in files if f["type"] == "file" and f["name"].endswith(".yaml")]
    slugs = sorted(n for n in names if TEAM_NAME.match(n) and n not in EXCLUDED_TEAMS)
    logger.info("Found %d teams (excluding %s)", len(slugs), ", ".join(EXCLUDED_TEAMS))
    for slug in slugs:
        logger.info("  %s", slug)
    return slugs


def write_tfvars(teams, output_path):
    """Write the registered-teams.auto.tfvars file."""
    lines = [
        "# GENERATED by sync-registered-teams.py — do not edit manually",
        "# Source of truth: teams/*.yaml in javaBin/registry",
        "",
        "registered_teams = [",
    ]
    for team in teams:
        lines.append(f'  "{team}",')
    lines.append("]")
    lines.append("")

    content = "\n".join(lines)

    existing = ""
    if os.path.exists(output_path):
        with open(output_path) as f:
            existing = f.read()

    if content == existing:
        logger.info("No changes to registered teams")
        return False

    with open(output_path, "w") as f:
        f.write(content)
    logger.info("Wrote %d teams to %s", len(teams), output_path)
    return True


def main():
    if len(sys.argv) != 2:
        print(f"Usage: {sys.argv[0]} <tfvars-output-path>", file=sys.stderr)
        sys.exit(1)

    output_path = sys.argv[1]
    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if not token:
        print("GITHUB_TOKEN or GH_TOKEN required", file=sys.stderr)
        sys.exit(1)

    teams = get_teams(token)
    write_tfvars(teams, output_path)


if __name__ == "__main__":
    main()
